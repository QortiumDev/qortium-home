async function attestSingleFileMime(filename, sourceBytes, mimeType) {
  const compression = sourceBytes.length <= 228 ? 0 : 1;
  const packaged = compression === 0 ? sourceBytes : zipSync({ [`data/${filename}`]: sourceBytes });
  const encrypted = encrypt(packaged);
  const encryptedHash = hash(encrypted.bytes);
  const metadataBytes = encoder.encode(JSON.stringify({
    title: 'MIME fixture',
    tags: [],
    chunks: [],
    files: [filename],
    mimeType,
  }));
  const metadataBytesHash = hash(metadataBytes);
  return attestPublicQdnPublish({
    details: {
      compression,
      data: encryptedHash,
      dataType: 0,
      metadataHash: metadataBytesHash,
      rawSize: encrypted.bytes.length,
      secret: encrypted.key,
    },
    expectedMetadata: { tags: [], title: 'MIME fixture' },
    fetchArtifact: fetchFrom(new Map([
      [hashKey(encryptedHash), encrypted.bytes],
      [hashKey(metadataBytesHash), metadataBytes],
    ])),
    source: { bytes: sourceBytes, filename, unpackZip: false },
  });
}

