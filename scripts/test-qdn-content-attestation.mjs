const BASE58_ALPHABET = '123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz';
const BASE58_MAP = new Map([...BASE58_ALPHABET].map((character, index) => [character, index]));

function decodeBase58(value) {
  const bytes = [0];
  for (const character of value) {
    const digit = BASE58_MAP.get(character);
    if (digit === undefined) throw new Error('invalid fixture Base58');
    let carry = digit;
    for (let index = 0; index < bytes.length; index += 1) {
      const next = bytes[index] * 58 + carry;
      bytes[index] = next & 0xff;
      carry = next >> 8;
    }
    while (carry > 0) {
      bytes.push(carry & 0xff);
      carry >>= 8;
    }
  }
  for (let index = 0; value[index] === '1' && index < value.length - 1; index += 1) bytes.push(0);
  return Uint8Array.from(bytes.reverse());
}

function encodeBase58(input) {
  if (input.length === 0) return '';
  const digits = [0];
  for (const byte of input) {
    let carry = byte;
    for (let index = 0; index < digits.length; index += 1) {
      const next = digits[index] * 256 + carry;
      digits[index] = next % 58;
      carry = Math.floor(next / 58);
    }
    while (carry > 0) {
      digits.push(carry % 58);
      carry = Math.floor(carry / 58);
    }
  }
  let result = '';
  for (let index = 0; index < input.length - 1 && input[index] === 0; index += 1) result += '1';
  for (let index = digits.length - 1; index >= 0; index -= 1) result += BASE58_ALPHABET[digits[index]];
  return result;
}

function hash(bytes) {
  return new Uint8Array(createHash('sha256').update(bytes).digest());
}

function encrypt(plaintext, key = randomBytes(32), nonce = randomBytes(12)) {
  const cipher = createCipheriv('aes-256-gcm', key, nonce);
  const ciphertext = Buffer.concat([cipher.update(plaintext), cipher.final(), cipher.getAuthTag()]);
  return {
    bytes: new Uint8Array(Buffer.concat([nonce, ciphertext])),
    key: new Uint8Array(key),
  };
}

function hashKey(bytes) {
  return Buffer.from(bytes).toString('hex');
}

function fetchFrom(artifacts) {
  return async (wantedHash) => {
    const artifact = artifacts.get(hashKey(wantedHash));
    if (!artifact) throw new Error('fixture artifact unavailable');
    return artifact;
  };
}

